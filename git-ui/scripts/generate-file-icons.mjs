// Writes client/file-icons.ts: the material-icon-theme SVGs Paseo's Changes view uses, keyed by the same
// extensions, with colours pulled toward neutral the way Paseo tones them (OKLab chroma × 0.65).
// Run after upgrading material-icon-theme: `npm run generate:icons`.
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const iconsDir = join(dirname(require.resolve("material-icon-theme/package.json")), "icons");
const out = join(dirname(fileURLToPath(import.meta.url)), "..", "client", "file-icons.ts");

const CHROMA = 0.65;

const EXTENSIONS = {
  astro: "astro", bash: "console", c: "c", cfg: "settings", clj: "clojure", conf: "settings", cpp: "cpp",
  cs: "csharp", css: "css", dart: "dart", erl: "erlang", ex: "elixir", exs: "elixir", gif: "image", go: "go",
  gql: "graphql", gradle: "gradle", graphql: "graphql", groovy: "groovy", h: "h", hcl: "hcl", hpp: "hpp",
  hs: "haskell", html: "html", ico: "image", ini: "settings", java: "java", jpeg: "image", jpg: "image",
  js: "javascript", json: "json", jsx: "react", kt: "kotlin", less: "less", lock: "lock", lua: "lua",
  markdown: "markdown", md: "markdown", ml: "ocaml", nix: "nix", php: "php", png: "image", py: "python", r: "r",
  rb: "ruby", rs: "rust", scala: "scala", scss: "sass", sh: "console", sql: "database", svelte: "svelte",
  svg: "svg", swift: "swift", tf: "terraform", toml: "toml", ts: "typescript", tsx: "react_ts", txt: "document",
  vue: "vue", wasm: "webassembly", webp: "image", xml: "xml", yaml: "yaml", yml: "yaml", zig: "zig",
};

const toLinear = (c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4);
const fromLinear = (c) => (c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055);
const channel = (c) => Math.round(Math.min(1, Math.max(0, fromLinear(c))) * 255).toString(16).padStart(2, "0");

/** Scales a colour's OKLab chroma, keeping its perceived lightness. */
function tone(hex) {
  const digits = hex.slice(1);
  const full = digits.length === 3 ? [...digits].map((d) => d + d).join("") : digits.length === 6 ? digits : null;
  if (!full) return hex;
  const [r, g, b] = [0, 2, 4].map((i) => toLinear(parseInt(full.slice(i, i + 2), 16) / 255));
  const l = Math.cbrt(0.4122214708 * r + 0.5363325363 * g + 0.0514459929 * b);
  const m = Math.cbrt(0.2119034982 * r + 0.6806995451 * g + 0.1073969566 * b);
  const s = Math.cbrt(0.0883024619 * r + 0.2817188376 * g + 0.6299787005 * b);
  const L = 0.2104542553 * l + 0.793617785 * m - 0.0040720468 * s;
  const A = (1.9779984951 * l - 2.428592205 * m + 0.4505937099 * s) * CHROMA;
  const B = (0.0259040371 * l + 0.7827717662 * m - 0.808675766 * s) * CHROMA;
  const l2 = (L + 0.3963377774 * A + 0.2158037573 * B) ** 3;
  const m2 = (L - 0.1055613458 * A - 0.0638541728 * B) ** 3;
  const s2 = (L - 0.0894841775 * A - 1.291485548 * B) ** 3;
  return `#${channel(4.0767416621 * l2 - 3.3077115913 * m2 + 0.2309699292 * s2)}${channel(-1.2684380046 * l2 + 2.6097574011 * m2 - 0.3413193965 * s2)}${channel(-0.0041960863 * l2 - 0.7034186147 * m2 + 1.707614701 * s2)}`;
}

const names = ["file", ...new Set(Object.values(EXTENSIONS))].sort();
const icons = Object.fromEntries(
  names.map((name) => {
    const svg = readFileSync(join(iconsDir, `${name}.svg`), "utf8").trim().replace(/\s*\n\s*/g, " ");
    return [name, svg.replace(/#[0-9a-fA-F]{3,6}\b/g, tone)];
  }),
);

const body = `// Generated by scripts/generate-file-icons.mjs from material-icon-theme (MIT). Do not edit.

export const FILE_ICON_SVGS: Record<string, string> = ${JSON.stringify(icons, null, 2)};

export const FILE_ICON_BY_EXTENSION: Record<string, string> = ${JSON.stringify(EXTENSIONS, null, 2)};
`;
writeFileSync(out, body);
console.log(`Wrote ${names.length} icons to ${out}`);
